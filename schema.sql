CREATE TABLE users (
 id TINYINT UNSIGNED PRIMARY KEY, role ENUM('owner','partner') NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, nickname VARCHAR(60) NOT NULL,
 avatar_file VARCHAR(100) NULL, last_seen DATETIME NULL,
 session_version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE user_sessions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id TINYINT UNSIGNED NOT NULL,
 session_hash CHAR(64) NOT NULL UNIQUE, session_version INT UNSIGNED NOT NULL,
 last_active DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, expires_at DATETIME NOT NULL,
 INDEX idx_sessions_user(user_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 sender_id TINYINT UNSIGNED NOT NULL, body TEXT NULL,
 message_type ENUM('text','media','voice') NOT NULL DEFAULT 'text',
 reply_to BIGINT UNSIGNED NULL, edited_at DATETIME NULL, deleted_for_all_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_msg_time(id,created_at), FOREIGN KEY(sender_id) REFERENCES users(id),
 FOREIGN KEY(reply_to) REFERENCES messages(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE message_receipts (
 message_id BIGINT UNSIGNED NOT NULL, user_id TINYINT UNSIGNED NOT NULL,
 delivered_at DATETIME NULL, read_at DATETIME NULL,
 PRIMARY KEY(message_id,user_id), FOREIGN KEY(message_id) REFERENCES messages(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE message_hides (
 message_id BIGINT UNSIGNED NOT NULL, user_id TINYINT UNSIGNED NOT NULL,
 PRIMARY KEY(message_id,user_id), FOREIGN KEY(message_id) REFERENCES messages(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE media_attachments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 message_id BIGINT UNSIGNED NOT NULL, stored_name CHAR(64) NOT NULL UNIQUE,
 original_name VARCHAR(255) NOT NULL, mime_type VARCHAR(120) NOT NULL,
 size_bytes BIGINT UNSIGNED NOT NULL, deleted_at DATETIME NULL,
 FOREIGN KEY(message_id) REFERENCES messages(id) ON DELETE CASCADE, INDEX idx_media_msg(message_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE message_reactions (
 message_id BIGINT UNSIGNED NOT NULL, user_id TINYINT UNSIGNED NOT NULL,
 emoji VARCHAR(24) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(message_id,user_id), FOREIGN KEY(message_id) REFERENCES messages(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE favorite_messages (
 message_id BIGINT UNSIGNED NOT NULL, user_id TINYINT UNSIGNED NOT NULL,
 PRIMARY KEY(message_id,user_id), FOREIGN KEY(message_id) REFERENCES messages(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE user_settings (
 user_id TINYINT UNSIGNED PRIMARY KEY, theme VARCHAR(24) NOT NULL DEFAULT 'dark',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE shared_notes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, author_id TINYINT UNSIGNED NOT NULL,
 body TEXT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(author_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE shared_settings (
 setting_key VARCHAR(40) PRIMARY KEY, setting_value VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE login_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, address_hash CHAR(64) NOT NULL,
 successful TINYINT(1) NOT NULL DEFAULT 0, attempted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_login_ratelimit(address_hash,attempted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE recovery_codes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id TINYINT UNSIGNED NOT NULL,
 code_hash VARCHAR(255) NOT NULL, used_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE security_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id TINYINT UNSIGNED NULL,
 event_type VARCHAR(50) NOT NULL, address_hash CHAR(64) NOT NULL,
 happened_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE typing_status (
 user_id TINYINT UNSIGNED PRIMARY KEY, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE message_changes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, message_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX idx_changes_id(id),
 FOREIGN KEY(message_id) REFERENCES messages(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE action_limits (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id TINYINT UNSIGNED NOT NULL, action_name VARCHAR(30) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_rate_user_action(user_id,action_name,created_at),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
